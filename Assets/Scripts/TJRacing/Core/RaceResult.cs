// TJ Racing 3D — race result payload sent to Flutter.
// Unity NEVER credits coins. It reports the result; Flutter calls the server
// (claim-race-level) which validates the race id, credits once, enforces the cap.
using System;
using UnityEngine;

namespace TJRacing
{
    [Serializable]
    public class RaceResult
    {
        public string type = "race_result";
        public string race_id;        // unique per race, generated by Unity (Guid)
        public string track_id = "night_city_1";
        public string car_id = "street_hawk";
        public int position;          // 1..6
        public int total_racers = 6;
        public int laps_completed;
        public float race_time_secs;
        public float best_lap_secs;
        public int level_coins_earned; // informational only: win 10 / 2nd 5 / else 0.
                                      // Flutter MUST re-derive this server-side; never trust this field.
        public bool is_first_race;

        public string ToJson() { return JsonUtility.ToJson(this); }
    }

    [Serializable]
    public class UnityEvent
    {
        public string type;           // e.g. "rewarded_completed", "interstitial_shown", "race_started"
        public string placement;      // ad placement id, when relevant
        public string race_id;
        public string detail;         // free-form extra info (JSON string or plain text)

        public string ToJson() { return JsonUtility.ToJson(this); }
    }
}
